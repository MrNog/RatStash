body = body.replace("OkanvilRaidLoot = {", "ns.RAIDLOOT = {", 1)
head = ("-- Every drop per raid, per boss, per difficulty: copied from Okanvil's RaidLoot-Data.lua\n"
        "-- (generated there from AtlasLoot's WotLK tables). `m` lists the difficulties an item drops in.\n"
        "-- Generated by scripts/gen_data.py, do not edit by hand.\n"
        "local _, ns = ...\n\n")
open(os.path.join(out_dir, "RaidLoot.lua"), "w", encoding="utf-8", newline="\n").write(head + body)
print("RaidLoot.lua:", body.count("{ id ="), "items")
