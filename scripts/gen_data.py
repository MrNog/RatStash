# ---- BiS lists ---------------------------------------------------------------------------
src = open(os.path.join(bt_dir, "Bistooltip_wowtbc_bislists.lua"), encoding="utf-8-sig").read()
row_re = re.compile(
    r'^Bistooltip_wowtbc_bislists\["([^"]+)"\]\["([^"]+)"\]\["([^"]+)"\]\[(\d+)\] = \{ \["slot_name"\] = "([^"]+)"(.*)\}\s*$',
    re.M)
lists = {}
for cls, spec, phase, idx, slot, rest in row_re.findall(src):
    # ranked ids are "[n] = 12345"; the enchant/gem block uses "[n] = { ... }" and is skipped
    ids = [int(v) for _, v in re.findall(r'\[(\d)\] = (\d+)', rest)]
    lists.setdefault(cls, {}).setdefault(spec, {}).setdefault(phase, []).append((int(idx), slot, ids))
phases = re.search(r'Bistooltip_wowtbc_phases = \{([^}]*)\}', src).group(1)

h2a_src = open(os.path.join(bt_dir, "Bistooltip_horde_to_ali.lua"), encoding="utf-8-sig").read()
h2a = re.findall(r'Bistooltip_horde_to_ali\[(\d+)\] = (\d+);', h2a_src)

out = [MIT, "-- Generated by scripts/gen_data.py, do not edit by hand.",
       "-- ns.BIS[class][spec][phase] = { { slot = \"Finger\", id1, id2, ... up to 6 (1 = BiS) }, ... }",
       "local _, ns = ...", "", "ns.BIS_PHASES = {" + phases + "}", "ns.BIS = {"]
rows = 0
for cls in sorted(lists):
    out.append(f'\t["{cls}"] = {{')
    for spec in sorted(lists[cls]):
        out.append(f'\t\t["{spec}"] = {{')
        for phase in sorted(lists[cls][spec]):
            out.append(f'\t\t\t["{phase}"] = {{')
            for idx, slot, ids in sorted(lists[cls][spec][phase]):
                out.append(f'\t\t\t\t{{ slot = "{slot}", ' + ", ".join(map(str, ids)) + " },")
                rows += 1
            out.append("\t\t\t},")
        out.append("\t\t},")
    out.append("\t},")
out.append("}")
out.append("")
out.append("-- Horde ToC ids -> the alliance ids the lists use")
out.append("ns.BIS_HORDE_TO_ALI = {")
for h, a in h2a:
    out.append(f"\t[{h}] = {a},")
out.append("}")
open(os.path.join(out_dir, "BisData.lua"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("BisData.lua:", rows, "rows,", len(h2a), "horde ids")

# ---- raid loot ---------------------------------------------------------------------------
loot = open(os.path.join(okv_dir, "RaidLoot-Data.lua"), encoding="utf-8").read()
body = loot[loot.index("OkanvilRaidLoot = {"):]
body = body.replace("OkanvilRaidLoot = {", "ns.RAIDLOOT = {", 1)
head = ("-- Every drop per raid, per boss, per difficulty: copied from Okanvil's RaidLoot-Data.lua\n"
        "-- (generated there from AtlasLoot's WotLK tables). `m` lists the difficulties an item drops in.\n"
        "-- Generated by scripts/gen_data.py, do not edit by hand.\n"
        "local _, ns = ...\n\n")
open(os.path.join(out_dir, "RaidLoot.lua"), "w", encoding="utf-8", newline="\n").write(head + body)
print("RaidLoot.lua:", body.count("{ id ="), "items")
